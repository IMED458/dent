export function normalizeIcd(code: string) {
  return code.trim().toUpperCase().replace(/,/g, '.').replace(/\s+/g, '');
}

export function searchIcd(list: IcdEntry[], q: string, limit = 30): IcdEntry[] {
  const s = q.trim().toLowerCase();
  if (!s) return list.slice(0, limit);
  const code = normalizeIcd(q);
  const byCode = list.filter((e) => e.code.toUpperCase().startsWith(code));
  const byText = list.filter((e) => !byCode.includes(e) && e.text.toLowerCase().includes(s));
  return [...byCode, ...byText].slice(0, limit);
}
